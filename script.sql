-- BRModelo - Sistema de Acompanhamento de Demandas
-- Projeto Integrador 2 - Oracle Database

CREATE TABLE USUARIOS (
    ID_USUARIO INT GENERATED BY DEFAULT AS IDENTITY,
    NOME VARCHAR2(120) NOT NULL,
    EMAIL VARCHAR2(150) NOT NULL,
    SENHA VARCHAR2(255) NOT NULL,
    PERFIL VARCHAR2(30) NOT NULL,
    ATIVO CHAR(1) DEFAULT 'S' NOT NULL,
    CONSTRAINT PK_USUARIOS PRIMARY KEY (ID_USUARIO),
    CONSTRAINT UK_USUARIOS_EMAIL UNIQUE (EMAIL),
    CONSTRAINT CK_USUARIOS_PERFIL CHECK (
        PERFIL IN ('Administrador', 'Lider de Projeto', 'Membro da Equipe')
    ),
    CONSTRAINT CK_USUARIOS_ATIVO CHECK (ATIVO IN ('S', 'N'))
);

CREATE TABLE PROJETOS (
    ID_PROJETO INT GENERATED BY DEFAULT AS IDENTITY,
    NOME VARCHAR2(120) NOT NULL,
    DESCRICAO VARCHAR2(500),
    DATA_INICIO DATE,
    DATA_FIM DATE,
    ATIVO CHAR(1) DEFAULT 'S' NOT NULL,
    CONSTRAINT PK_PROJETOS PRIMARY KEY (ID_PROJETO),
    CONSTRAINT CK_PROJETOS_DATAS CHECK (
        DATA_FIM IS NULL OR DATA_INICIO IS NULL OR DATA_FIM >= DATA_INICIO
    ),
    CONSTRAINT CK_PROJETOS_ATIVO CHECK (ATIVO IN ('S', 'N'))
);

CREATE TABLE PROJETO_USUARIO (
    ID_PROJETO INT NOT NULL,
    ID_USUARIO INT NOT NULL,
    CONSTRAINT PK_PROJETO_USUARIO PRIMARY KEY (ID_PROJETO, ID_USUARIO),
    CONSTRAINT FK_PU_PROJETO FOREIGN KEY (ID_PROJETO)
        REFERENCES PROJETOS (ID_PROJETO),
    CONSTRAINT FK_PU_USUARIO FOREIGN KEY (ID_USUARIO)
        REFERENCES USUARIOS (ID_USUARIO)
);

CREATE TABLE DEMANDAS (
    ID_DEMANDA INT GENERATED BY DEFAULT AS IDENTITY,
    TITULO VARCHAR2(150) NOT NULL,
    DESCRICAO VARCHAR2(2000),
    DATA_CRIACAO DATE DEFAULT SYSDATE NOT NULL,
    DATA_ATUALIZACAO DATE DEFAULT SYSDATE NOT NULL,
    PRAZO_FINALIZACAO DATE,
    PRIORIDADE VARCHAR2(10) NOT NULL,
    TIPO VARCHAR2(30) NOT NULL,
    STATUS VARCHAR2(30) NOT NULL,
    ID_PROJETO INT NOT NULL,
    ID_SOLICITANTE INT NOT NULL,
    ID_RESPONSAVEL INT,
    CONSTRAINT PK_DEMANDAS PRIMARY KEY (ID_DEMANDA),
    CONSTRAINT CK_DEMANDAS_PRIORIDADE CHECK (
        PRIORIDADE IN ('Critica', 'Alta', 'Media', 'Baixa')
    ),
    CONSTRAINT CK_DEMANDAS_TIPO CHECK (
        TIPO IN ('Tarefa', 'Defeito', 'Melhoria', 'Documentacao')
    ),
    CONSTRAINT CK_DEMANDAS_STATUS CHECK (
        STATUS IN ('Aberta', 'Em andamento', 'Em revisao', 'Concluida', 'Cancelada')
    ),
    CONSTRAINT FK_DEMANDAS_PROJETO FOREIGN KEY (ID_PROJETO)
        REFERENCES PROJETOS (ID_PROJETO),
    CONSTRAINT FK_DEMANDAS_SOLICITANTE FOREIGN KEY (ID_SOLICITANTE)
        REFERENCES USUARIOS (ID_USUARIO),
    CONSTRAINT FK_DEMANDAS_RESPONSAVEL FOREIGN KEY (ID_RESPONSAVEL)
        REFERENCES USUARIOS (ID_USUARIO)
);

CREATE TABLE COMENTARIOS (
    ID_COMENTARIO INT GENERATED BY DEFAULT AS IDENTITY,
    TEXTO VARCHAR2(2000) NOT NULL,
    DATA_HORA DATE DEFAULT SYSDATE NOT NULL,
    ID_DEMANDA INT NOT NULL,
    ID_USUARIO INT NOT NULL,
    CONSTRAINT PK_COMENTARIOS PRIMARY KEY (ID_COMENTARIO),
    CONSTRAINT FK_COMENTARIOS_DEMANDA FOREIGN KEY (ID_DEMANDA)
        REFERENCES DEMANDAS (ID_DEMANDA),
    CONSTRAINT FK_COMENTARIOS_USUARIO FOREIGN KEY (ID_USUARIO)
        REFERENCES USUARIOS (ID_USUARIO)
);

CREATE TABLE HISTORICOS (
    ID_HISTORICO INT GENERATED BY DEFAULT AS IDENTITY,
    CAMPO_ALTERADO VARCHAR2(50) NOT NULL,
    VALOR_ANTERIOR VARCHAR2(2000),
    VALOR_NOVO VARCHAR2(2000),
    DATA_ALTERACAO DATE DEFAULT SYSDATE NOT NULL,
    ID_DEMANDA INT NOT NULL,
    ID_USUARIO INT NOT NULL,
    CONSTRAINT PK_HISTORICOS PRIMARY KEY (ID_HISTORICO),
    CONSTRAINT FK_HISTORICOS_DEMANDA FOREIGN KEY (ID_DEMANDA)
        REFERENCES DEMANDAS (ID_DEMANDA),
    CONSTRAINT FK_HISTORICOS_USUARIO FOREIGN KEY (ID_USUARIO)
        REFERENCES USUARIOS (ID_USUARIO)
);

COMMIT;
